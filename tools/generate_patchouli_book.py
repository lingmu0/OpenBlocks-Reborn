"""Generate the Patchouli manual from registries and the legacy 1.12.2 manual.

The generated book follows the legacy sections. Running this script after
adding a block or item keeps the Patchouli manual complete.
"""

from __future__ import annotations

import json
import math
import re
import textwrap
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
JAVA_ROOT = ROOT / "src/main/java/net/xuwu/openblocks_reborn/registry"
RESOURCE_ROOT = ROOT / "src/main/resources"
BOOK_ID = "openblocks_guide"
BOOK_ROOT = RESOURCE_ROOT / "assets/openblocks_reborn/patchouli_books" / BOOK_ID / "en_us"
DESCRIPTION_PATH = ROOT / "tools/guide_descriptions.json"

CATEGORIES = {
    "introduction": ("openblocks_reborn:info_book", -10),
    "blocks": ("openblocks_reborn:guide", 0),
    "items": ("openblocks_reborn:hang_glider", 10),
    "misc": ("minecraft:enchanted_book", 20),
    "changelogs": ("minecraft:writable_book", 30),
}


def write_json(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def registry_ids(source_name: str) -> list[str]:
    source = (JAVA_ROOT / source_name).read_text(encoding="utf-8")
    return re.findall(r'\bregister\("([a-z0-9_]+)"', source)


def standalone_item_ids() -> list[str]:
    source = (JAVA_ROOT / "ModItems.java").read_text(encoding="utf-8")
    return re.findall(r'\b(?:register|item)\("([a-z0-9_]+)"', source)


def category(item_id: str, is_block: bool) -> str:
    return "blocks" if is_block else "items"


def legacy_pages(text: str, locale: str) -> list[str]:
    # Leave room for the title in the 115px Patchouli text column.
    if locale == "zh_cn":
        width = math.ceil(len(text) / max(1, math.ceil(len(text) / 120)))
        return [text[i:i + width] for i in range(0, len(text), width)]
    width = math.ceil(len(text) / max(1, math.ceil(len(text) / 300)))
    return textwrap.wrap(text, width=max(1, width), break_long_words=False, replace_whitespace=False)


def main() -> None:
    # This directory is generated by this script; remove stale category/entry paths.
    for folder in (BOOK_ROOT / "categories", BOOK_ROOT / "entries"):
        for path in folder.rglob("*.json"):
            path.unlink()
    block_ids = registry_ids("ModBlocks.java")
    block_ids += ["elevator_" + color for color in
                  "white orange magenta light_blue yellow lime pink gray light_gray cyan purple blue brown green red black".split()]
    item_ids = standalone_item_ids()
    entries = [(item_id, True) for item_id in block_ids]
    entries.extend((item_id, False) for item_id in item_ids)
    entries.append(("xp_bucket", False))
    if len(entries) != len({item_id for item_id, _ in entries}):
        raise RuntimeError("Duplicate OpenBlocks registry IDs cannot be represented in the manual")
    descriptions = json.loads(DESCRIPTION_PATH.read_text(encoding="utf-8"))
    legacy = json.loads((ROOT / "tools/legacy_guide.json").read_text(encoding="utf-8"))
    historical = {}
    for item_id, is_block in entries:
        key = f"{'tile' if is_block else 'item'}.openblocks.{item_id}.description"
        if key in legacy["en_us"]:
            historical[item_id] = {locale: legacy_pages(legacy[locale].get(key, legacy["en_us"][key]), locale)
                                   for locale in ("zh_cn", "en_us")}
    entry_ids = {item_id for item_id, _ in entries}
    missing = sorted(entry_ids - descriptions.keys())
    extra = sorted(descriptions.keys() - entry_ids)
    if missing or extra:
        raise RuntimeError(
            f"Guide descriptions do not match registries; missing={missing}, extra={extra}"
        )
    for item_id, localized in descriptions.items():
        if set(localized) != {"zh_cn", "en_us"} or not all(localized.values()):
            raise RuntimeError(f"Guide description for {item_id} must contain non-empty zh_cn and en_us")
    current_pages = {item_id: {locale: legacy_pages(text, locale) for locale, text in localized.items()}
                     for item_id, localized in descriptions.items()}
    enchantment_text = json.loads((ROOT / "tools/enchantment_text.json").read_text(encoding="utf-8"))
    enchantment_parts = {enchantment: {locale: legacy_pages(
        enchantment_text[locale][f"message.openblocks_reborn.book.enchantment.{enchantment}"], locale)
        for locale in ("en_us", "zh_cn")} for enchantment in ("flim_flam", "unstable", "last_stand")}

    for locale in ("zh_cn", "en_us"):
        lang_path = RESOURCE_ROOT / f"assets/openblocks_reborn/lang/{locale}.json"
        lang = json.loads(lang_path.read_text(encoding="utf-8-sig"))
        extra = ROOT / "tools/highlighter_lang.json"
        if extra.exists():
            lang.update(json.loads(extra.read_text(encoding="utf-8"))[locale])
        for key, value in enchantment_text[locale].items():
            lang[key] = value
        for enchantment in ("flim_flam", "unstable", "last_stand"):
            parts = enchantment_parts[enchantment]
            for index in range(max(map(len, parts.values()))):
                lang[f"patchouli.openblocks_reborn.enchantment.{enchantment}.{index}"] = (
                    parts[locale][index] if index < len(parts[locale]) else "—")
        category_text = {
            "introduction": ("欢迎与致谢", "Welcome & credits", "指南的开篇与作者致谢。", "Welcome and author acknowledgements."),
            "blocks": ("方块", "Blocks", "按旧版指南归类的方块与设备。", "Blocks and devices, following the legacy manual."),
            "items": ("物品", "Items", "工具、装备、材料与液体容器。", "Tools, equipment, components and fluid containers."),
            "misc": ("杂项", "Miscellaneous", "配置、附魔以及与旧版的功能差异。", "Configuration, enchantments and legacy differences."),
            "changelogs": ("更新日志", "Changelogs", "本次重制的变更记录。", "Changes in this redux build."),
        }
        for key, (zh, en, zh_desc, en_desc) in category_text.items():
            lang[f"message.openblocks_reborn.book.category.{key}"] = zh if locale == "zh_cn" else en
            lang[f"message.openblocks_reborn.book.category.{key}.description"] = zh_desc if locale == "zh_cn" else en_desc
        for item_id, _ in entries:
            lang[f"message.openblocks_reborn.book.detail.{item_id}"] = descriptions[item_id][locale]
            localized = current_pages[item_id]
            for index in range(max(map(len, localized.values()))):
                lang[f"patchouli.openblocks_reborn.current.{item_id}.{index}"] = (
                    localized[locale][index] if index < len(localized[locale]) else "—")
        lang["patchouli.openblocks_reborn.legacy.title"] = "1.12.2 旧版参考" if locale == "zh_cn" else "1.12.2 reference"
        lang["patchouli.openblocks_reborn.legacy.notice"] = (
            "以下摘自 1.12.2 指南，供理解原设计。操作与限制请以本条目的当前版本说明为准。"
            if locale == "zh_cn" else
            "From the 1.12.2 manual, for historical context. Follow this entry's current instructions and limits."
        )
        for item_id, localized in historical.items():
            count = max(map(len, localized.values()))
            for index in range(count):
                lang[f"patchouli.openblocks_reborn.legacy.{item_id}.{index}"] = (
                    localized[locale][index] if index < len(localized[locale]) else "—")
        write_json(lang_path, lang)

    write_json(
        RESOURCE_ROOT / "data/openblocks_reborn/patchouli_books" / BOOK_ID / "book.json",
        {
            "name": "item.openblocks_reborn.info_book",
            "landing_text": "patchouli.openblocks_reborn.book.landing",
            "subtitle": "patchouli.openblocks_reborn.book.subtitle",
            "version": "0",
            "book_texture": "patchouli:textures/gui/book_green.png",
            "use_resource_pack": True,
            "dont_generate_book": True,
            "custom_book_item": "openblocks_reborn:info_book",
            "show_progress": False,
            "show_toasts": False,
            "use_blocky_font": True,
            "i18n": True,
        },
    )

    for category_id, (icon, sortnum) in CATEGORIES.items():
        title_key = f"message.openblocks_reborn.book.category.{category_id}"
        write_json(
            BOOK_ROOT / "categories" / f"{category_id}.json",
            {
                "name": title_key,
                "description": f"{title_key}.description",
                "icon": icon,
                "sortnum": sortnum,
            },
        )

    counts = {category_id: 0 for category_id in CATEGORIES}
    recipe_root = RESOURCE_ROOT / "data/openblocks_reborn/recipe"
    for item_id, is_block in entries:
        category_id = category(item_id, is_block)
        counts[category_id] += 1
        description = f"patchouli.openblocks_reborn.current.{item_id}.0"
        display_item = f"openblocks_reborn:{item_id}"
        pages: list[dict[str, object]] = [
            {
                "type": "patchouli:spotlight",
                "item": display_item,
                "text": description,
                "link_recipe": True,
            }
        ]
        for index in range(1, max(map(len, current_pages[item_id].values()))):
            pages.append({"type": "patchouli:text",
                          "text": f"patchouli.openblocks_reborn.current.{item_id}.{index}"})
        if (recipe_root / f"{item_id}.json").is_file():
            pages.append({
                "type": "patchouli:crafting",
                "recipe": f"openblocks_reborn:{item_id}",
            })
        old_key = f"{'tile' if is_block else 'item'}.openblocks.{item_id}.description"
        # Historical pages are explicitly separated from current instructions.
        # Missing/changed controls are never presented as working modern features.
        if old_key in legacy["en_us"]:
            pages.append({"type": "patchouli:text", "title": "patchouli.openblocks_reborn.legacy.title",
                          "text": "patchouli.openblocks_reborn.legacy.notice"})
            for index in range(max(map(len, historical[item_id].values()))):
                pages.append({"type": "patchouli:text", "title": "patchouli.openblocks_reborn.legacy.title",
                              "text": f"patchouli.openblocks_reborn.legacy.{item_id}.{index}"})
        name_prefix = "block" if is_block else "item"
        write_json(
            BOOK_ROOT / "entries" / category_id / f"{item_id}.json",
            {
                "name": f"{name_prefix}.openblocks_reborn.{item_id}",
                "icon": display_item,
                "category": f"openblocks_reborn:{category_id}",
                "read_by_default": True,
                "sortnum": counts[category_id],
                "pages": pages,
            },
        )

    enchantment_pages = []
    # Emit separate translated pages so detailed explanations fit the book column.
    for enchantment in ("flim_flam", "unstable", "last_stand"):
        length = max(map(len, enchantment_parts[enchantment].values()))
        for index in range(length):
            enchantment_pages.append({"type": "patchouli:text", "title": f"enchantment.openblocks_reborn.{enchantment}",
                                      "text": f"patchouli.openblocks_reborn.enchantment.{enchantment}.{index}"})
    write_json(
        BOOK_ROOT / "entries/misc/enchantments.json",
        {
            "name": "message.openblocks_reborn.book.enchantments",
            "icon": "minecraft:enchanted_book",
            "category": "openblocks_reborn:misc",
            "read_by_default": True,
            "sortnum": 10,
            "pages": enchantment_pages,
        },
    )

    sections = json.loads((ROOT / "tools/guide_sections.json").read_text(encoding="utf-8"))
    for locale in ("en_us", "zh_cn"):
        for entry_id, section in sections.items():
            localized = section[locale]
            write_json(BOOK_ROOT.parent / locale / "entries" / (entry_id + ".json"), {
                "name": localized["name"], "icon": section["icon"],
                "category": "openblocks_reborn:" + section["category"], "read_by_default": True,
                "sortnum": 0,
                "pages": [{"type": "patchouli:text", "title": localized["name"], "text": page}
                          for page in legacy_pages(localized["text"], locale)]
            })

    print(
        f"Generated Patchouli manual: {len(entries)} item entries plus enchantments "
        f"in {len(CATEGORIES)} categories"
    )
    print("Category counts: " + ", ".join(f"{key}={value}" for key, value in counts.items()))


if __name__ == "__main__":
    main()
